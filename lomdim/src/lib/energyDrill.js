// "חשמלית" → "אנרגיה חשמלית", "גובה" → "אנרגיית גובה"
const NAME = { 'כימית': 'אנרגיה כימית', 'חשמלית': 'אנרגיה חשמלית' }
export const nameOf = (f) => NAME[f] || `אנרגיית ${f}`
const r5 = (lo, hi) => 5 * R(Math.ceil(lo / 5), Math.floor(hi / 5))

export function makePie(lv) {
  const dv = pick(DEVICES)
  const pct = r5(dv.p[0], dv.p[1])
  const total = pick([100, 200, 400, 500, 1000, 2000])
  const use = total * pct / 100, waste = total - use
  const law = ['חוק שימור האנרגיה: האנרגיה בהתחלה = סך האנרגיה בסוף', `${nameOf(dv.from)} = ${nameOf(dv.use)} + חום`]
  const base = { kind: 'pie', d: dv.d, from: dv.from, use: dv.use, pct }
  if (lv === 1 || (lv === 2 && Math.random() < 0.5)) {
    // ידועות ההתחלה ואחד החלקים — מוצאים את החלק השני
    const askWaste = lv === 1 || Math.random() < 0.5
    return { ...base, total, slices: [[dv.use, askWaste ? use : '?'], ['חום', askWaste ? '?' : waste]],
      q: askWaste
        ? `ל${dv.d} נכנסו ${total} ג'ול של ${nameOf(dv.from)}. ${use} ג'ול הפכו ל${nameOf(dv.use)}, והשאר הפך לחום. כמה ג'ול הפכו לחום?`
        : `ל${dv.d} נכנסו ${total} ג'ול של ${nameOf(dv.from)}. ${waste} ג'ול הפכו לחום. כמה ג'ול הפכו ל${nameOf(dv.use)}?`,
      ans: askWaste ? waste : use, unit: "ג'ול",
      steps: [law, ['מציבים את המספרים', `${total} = ${askWaste ? use : '?'} + ${askWaste ? '?' : waste}`],
        ['מחסרים', `? = ${total} − ${askWaste ? use : waste}`], ['התשובה', `${askWaste ? waste : use} ג'ול`, true]] }
  }
  if (lv === 2) {
    // באחוזים: כל העוגה היא 100%
    return { ...base, total: null, slices: [[dv.use, `${pct}%`], ['חום', '?']],
      q: `ב${dv.d}, ${pct}% מהאנרגיה שנכנסת הופכים ל${nameOf(dv.use)}. כמה אחוז הופכים לחום?`,
      ans: 100 - pct, unit: '%',
      steps: [['כל האנרגיה שנכנסה היא 100% — העוגה כולה', `100% = ${pct}% + ?`], ['מחסרים', `? = 100 − ${pct}`], ['התשובה', `${100 - pct}%`, true]] }
  }
  // רמה 3: מג'ול לאחוזים
  return { ...base, total, slices: [[dv.use, use], ['חום', waste]],
    q: `ל${dv.d} נכנסו ${total} ג'ול של ${nameOf(dv.from)}, ו־${use} ג'ול מתוכם הפכו ל${nameOf(dv.use)}. כמה אחוז מהאנרגיה שנכנסה הפכו ל${nameOf(dv.use)}?`,
    ans: pct, unit: '%',
    steps: [['איזה חלק מהשלם?', `${use} : ${total}`], ['כופלים ב־100 כדי לקבל אחוזים', `${use} : ${total} · 100`], ['התשובה', `${pct}%`, true]] }
}

// גרף עוגה ב-SVG — שני חלקים (מועיל / חום), גודל לפי האחוזים
export function pieSVG(pct) {
  const C = 90, r = 80, a = (pct / 100) * Math.PI * 2
  const x = C + r * Math.sin(a), y = C - r * Math.cos(a)
  const big = pct > 50 ? 1 : 0
  return `<svg viewBox="0 0 180 180" role="img" aria-label="גרף עוגה">
<circle cx="${C}" cy="${C}" r="${r}" fill="var(--accent)"/>
<path d="M${C},${C} L${C},${C - r} A${r},${r} 0 ${big} 1 ${x},${y} Z" fill="var(--primary)"/>
<circle cx="${C}" cy="${C}" r="${r}" fill="none" stroke="var(--bg)" stroke-width="2"/>
<line x1="${C}" y1="${C}" x2="${C}" y2="${C - r}" stroke="var(--bg)" stroke-width="2"/>
<line x1="${C}" y1="${C}" x2="${x}" y2="${y}" stroke="var(--bg)" stroke-width="2"/>
</svg>`
}

